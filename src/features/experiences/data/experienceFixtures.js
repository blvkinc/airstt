const buildOccurrences = (date, time, occurrences = DEFAULT_OCCURRENCES) => {
  const start = new Date(date)
  return occurrences.map((occurrence, index) => {
    const value = new Date(start)
    value.setDate(start.getDate() + occurrence.suffix)
    return {
      date: value.toISOString().slice(0, 10),
      time,
      status: occurrence.status,
      packagesAvailable: occurrence.packagesAvailable,
      id: `${value.toISOString().slice(0, 10)}-${index}`
    }
  })
}

